export function schoolCertificateAuthorities() {
  const cert = new X509Certificate(HCMUE_INTERMEDIATE);
  const now = Date.now();
  const trusted = rootCertificates.some((pem) => {
    const root = new X509Certificate(pem);
    return cert.checkIssued(root) && cert.verify(root.publicKey);
  });
  if (
    !cert.ca ||
    cert.fingerprint256 !== PIN ||
    !trusted ||
    now < Date.parse(cert.validFrom) ||
    now > Date.parse(cert.validTo)
  )
    throw new Error(
      "Chuỗi chứng chỉ HCMUE cần cập nhật. Không tắt xác minh HTTPS.",
    );
  // Keep the default roots and strict hostname/time/signature verification.
  return [...getCACertificates("default"), HCMUE_INTERMEDIATE];
}
